ResolvePixelClock:
; Logical clocks describe scaled modes; the physical HDMI clock stays 66 MHz.
; a1: ModeInfo. Return d0=clock index; unsupported geometry gets clock zero Hz.
    movem.l d1/d2,-(sp)
    bsr ModeRepeat
    tst.l d0
    bmi.s .invalid
    move.l RepeatClocks(pc,d1.l*4),gmi_PixelClock(a1)
    clr.w gmi_Clock(a1)
    move.b d1,gmi_Clock(a1)
    andi.w #3,d0
    move.w RepeatHTotal(pc,d0.w*2),d2
    move.w d2,gmi_HorTotal(a1)
    sub.w gmi_Width(a1),d2
    move.w d2,gmi_HorBlankSize(a1)
    move.w RepeatHStart(pc,d0.w*2),gmi_HorSyncStart(a1)
    move.w RepeatHSize(pc,d0.w*2),gmi_HorSyncSize(a1)
    move.w d1,d0
    divu.w #3,d0
    andi.l #$ffff,d0
    move.w RepeatVTotal(pc,d0.w*2),d2
    move.w d2,gmi_VerTotal(a1)
    sub.w gmi_Height(a1),d2
    move.w d2,gmi_VerBlankSize(a1)
    move.w RepeatVStart(pc,d0.w*2),gmi_VerSyncStart(a1)
    move.w RepeatVSize(pc,d0.w*2),gmi_VerSyncSize(a1)
    move.l d1,d0
    bra.s .done
.invalid:
    clr.l gmi_PixelClock(a1)
    clr.w gmi_Clock(a1)
    moveq #0,d0
.done:
    movem.l (sp)+,d1/d2
    rts

;------------------------------------------------------------------------------
GetPixelClock:
; d0: index, d7: RGB format. Return logical frequency and bytes/source pixel.
    moveq #0,d1
    cmp.l #RGBFB_CLUT,d7
    beq.s .indexed
    cmp.l #RGBFB_R5G6B5,d7
    beq.s .direct
    cmp.l #RGBFB_R5G5B5,d7
    beq.s .direct
.invalid:
    moveq #0,d0
    rts
.indexed:
    moveq #1,d1
    bra.s .clock
.direct:
    moveq #2,d1
.clock:
    cmpi.l #9,d0
    bcc.s .invalid
    move.l RepeatClocks(pc,d0.l*4),d0
    rts

; Clock = 66 MHz * logical HTotal * logical VTotal / (1344 * 806).
; Vertical 3x uses 269 logical lines, so its clocks include the rounding.
; For a different raster, recompute these clocks from its physical pixel clock
