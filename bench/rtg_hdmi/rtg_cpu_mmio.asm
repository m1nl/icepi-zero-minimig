    move.w $b80000,d0
    cmp.w #$c0ca,d0
    bne fail
    move.w $b80002,d0
    cmp.w #$cafe,d0
    bne fail
    move.w $b8010e,d0
    cmp.w #$8321,d0
    bne fail
    move.w $b8010c,d0
    tst.w d0
    bne fail
    move.l #$00123450,$b80100
    move.l #$00567890,$b80108
    move.l #$00123456,$b80400
    move.l #$00654321,$b80404
    move.w $b80110,d0
    tst.w d0
    bne fail
    move.w #1,$b80110
    move.w $b80110,d0
    cmp.w #1,d0
    bne fail
    move.w #384,$b80112
    move.w $b80112,d0
    cmp.w #384,d0
    bne fail
    move.w #0,$b80110
    move.w $b80110,d0
    tst.w d0
    bne fail
    move.w $b8010e,d0
    cmp.w #$8321,d0
    bne fail
    move.w #$600d,$1000
