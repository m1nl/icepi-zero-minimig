    ; fallback before checking the separate word-sized MMIO transactions.
    move.l #$0101,d0
    movec d0,cacr
    cnop 0,4
    nop
    move.l #$12345678,d0
    move.l d0,$1400
    move.l $1400,d1
    cmp.l d0,d1
    bne fail
    move.b #$a5,$1401
    cmp.l #$12a55678,$1400
    bne fail
    move.l d0,$1406
    move.l $1406,d1
    cmp.l d0,d1
    bne fail
    move.l d0,$140e
    move.l $140e,d1
    cmp.l d0,d1
    bne fail
    ; Odd longwords require masked first/last words around the collected pair.
    move.l #$a5a5a5a5,$1430
    move.l #$a5a5a5a5,$1434
    move.l d0,$1431
    move.l $1431,d1
    cmp.l d0,d1
    bne fail
