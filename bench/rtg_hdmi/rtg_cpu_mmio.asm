    move.l $1453,d1
    cmp.l d0,d1
    bne fail
    cmp.b #$a5,$1452
    bne fail
    cmp.b #$a5,$1457
    bne fail
    move.l #$a5a5a5a5,$147c
    move.l #$a5a5a5a5,$1480
